/// What a page shows about one monitor (computed by the event loop).
#[derive(Clone, Debug, PartialEq)]
pub struct MonitorView {
    pub state: State,
    pub since: Option<i64>,
    pub last_check: Option<i64>,
    pub last_msg: String,
    pub last_error: Option<(i64, String)>,
    pub cert_expires: Option<i64>,
    pub beats: Vec<BeatRecord>,
    pub uptime_24h: Option<f64>,
    pub uptime_30d: Option<f64>,
    pub avg_ms_24h: Option<u32>,
    pub skipped_24h: u32,
    /// State changes (time, new state), oldest first.
    pub changes: Vec<(i64, State)>,
}

impl MonitorView {
    /// `maintenance`: start of the maintenance window the monitor is in now.
    pub fn new(h: &History, now: i64, maintenance: Option<i64>) -> Self {
        let day = h.last_hours(now, 24);
        let (state, since) = match maintenance {
            Some(start) => (State::Maintenance, Some(start)),
            None => (h.state, h.state_since),
        };
        MonitorView {
            state,
            since,
            last_check: h.last_check,
            last_msg: h.last_msg.clone(),
            last_error: h.last_error.clone(),
            cert_expires: h.cert_expires,
            beats: h.recent.iter().copied().collect(),
            uptime_24h: history::uptime_percent(&day),
            uptime_30d: history::uptime_percent(&h.last_days(now, 30)),
            avg_ms_24h: day.avg_ms(),
            skipped_24h: day.skipped,
            changes: h.changes.iter().copied().collect(),
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct SelfStatus {
    pub started: i64,
    pub queue_len: usize,
    pub workers: u32,
    pub skipped_24h: u32,
    pub last_render_ms: u64,
    /// Average response time of all successful checks in the last 24 h.
    pub avg_check_ms_24h: Option<u32>,
    /// Last successful flush of the check log (Unix seconds).
    pub last_flush: Option<i64>,
}

/// Input of one render. `monitors` is index-aligned with the configuration.
#[derive(Clone, Debug)]
pub struct Snapshot {
    pub now: i64,
    pub monitors: Vec<MonitorView>,
    pub status: SelfStatus,
}

/// A generated file.
#[derive(Debug, PartialEq)]
pub struct File {
    pub content_type: &'static str,
    pub body: Vec<u8>,
    pub private: bool,
}

/// All generated files by URL path (see the module documentation).
#[derive(Debug, Default)]
pub struct Site {
    pub files: HashMap<String, Arc<File>>,
}

/// The site currently served; replaced after every render.
pub type Published = Arc<RwLock<Arc<Site>>>;

/// Static inputs of the renderer.
pub struct Renderer {
    pub pages: Arc<Vec<Page>>,
    pub monitors: Arc<Vec<Monitor>>,
    pub tz: TimeZone,
    pub auto_refresh_s: u64,
    pub recent_checks: usize,
    pub css: String,
    pub output_dir: PathBuf,
    pub incidents: Arc<Vec<Incident>>,
    pub maintenance: Arc<Vec<Maintenance>>,
    /// For absolute links in feeds.
    pub base_url: Option<String>,
    /// Generate `/metrics` (SPEC.md §9.5).
    pub metrics: bool,
}

/// URL path of a generated file of a page.
fn page_url(page: &Page, file: &str) -> String {
    if page.public {
        format!("/{}/{file}", page.id)
    } else {
        format!("/private/{}/{file}", page.id)
    }
}

impl Renderer {
    pub fn css(custom: Option<&Path>) -> Result<String, String> {
        let mut css = DEFAULT_CSS.to_string();
        if let Some(path) = custom {
            let extra = fs::read_to_string(path)
                .map_err(|e| format!("pages.custom_css {}: {e}", path.display()))?;
            css.push_str("\n/* custom.css */\n");
            css.push_str(&extra);
        }
        Ok(css)
    }

    pub fn build(&self, snap: &Snapshot) -> Site {
        let ctx = html::Context {
            pages: &self.pages,
            monitors: &self.monitors,
            tz: &self.tz,
            auto_refresh_s: self.auto_refresh_s,
            recent_checks: self.recent_checks,
            incidents: &self.incidents,
            maintenance: &self.maintenance,
            now: snap.now,
        };
        let mut files = HashMap::new();
        let css = Arc::new(File {
            content_type: "text/css; charset=utf-8",
            body: self.css.clone().into_bytes(),
            private: false,
        });
        let icon = Arc::new(File {
            content_type: "image/svg+xml",
            body: FAVICON.as_bytes().to_vec(),
            private: false,
        });
        files.insert("/assets/kinomi.css".to_string(), css.clone());
        files.insert("/assets/favicon.svg".to_string(), icon.clone());
        if self.pages.iter().any(|p| !p.public) {
            for (name, file) in [("kinomi.css", &css), ("favicon.svg", &icon)] {
                let private = File {
                    content_type: file.content_type,
                    body: file.body.clone(),
                    private: true,
                };
                files.insert(format!("/private/assets/{name}"), Arc::new(private));
            }
        }
        for page in self.pages.iter() {
            let mut add = |name: &str, content_type: &'static str, body: String| {
                let file = File {
                    content_type,
                    body: body.into_bytes(),
                    private: !page.public,
                };
                files.insert(page_url(page, name), Arc::new(file));
            };
            add("", "text/html; charset=utf-8", html::page(&ctx, page, snap));
            add(
                "status.json",
                "application/json",
                json::status_json(&ctx, page, snap),
            );
            add(
                "feed.atom",
                "application/atom+xml; charset=utf-8",
                feed::feed(&ctx, page, snap, self.base_url.as_deref()),
            );
            if page.show_badges {
                let mut seen = Vec::new();
                for &i in page.groups.iter().flat_map(|g| g.monitors.iter()) {
                    if seen.contains(&i) {
                        continue;
                    }
                    seen.push(i);
                    let (m, v) = (&self.monitors[i], &snap.monitors[i]);
                    let state = json::state_name(m, v);
                    add(
                        &format!("badge/{}.svg", m.id),
                        "image/svg+xml",
                        badge::badge(&m.name, state, badge::color(state)),
                    );
                    let uptime = v.uptime_30d.map_or("–".to_string(), |p| {
                        format!("{:.2} %", (p * 100.0).floor() / 100.0)
                    });
                    let color = match v.uptime_30d {
                        Some(p) if p >= 99.0 => badge::color("UP"),
                        Some(p) if p >= 95.0 => badge::color("WARN"),
                        Some(_) => badge::color("DOWN"),
                        None => badge::color(""),
                    };
                    add(
                        &format!("badge/{}-uptime.svg", m.id),
                        "image/svg+xml",
                        badge::badge("uptime 30d", &uptime, color),
                    );
                }
            }
        }
        if self.metrics {
            let body = metrics::metrics(&self.monitors, snap).into_bytes();
            let file = File {
                content_type: "text/plain; version=0.0.4; charset=utf-8",
                body,
                private: true,
            };
            files.insert("/metrics".to_string(), Arc::new(file));
        }
        Site { files }
    }
}

/// File system path of a URL path below `output_dir`.
fn disk_path(output_dir: &Path, url: &str) -> PathBuf {
    let (top, rest) = match url.strip_prefix("/private/") {
        Some(rest) => ("private", rest),
        None => ("public", url.trim_start_matches('/')),
    };
    let mut path = output_dir.join(top).join(rest);
    if url.ends_with('/') {
        path.push("index.html");
    }
    path
}

/// Write changed files and remove page directories that are no longer
/// configured. Directories are 0750 and files 0640, so a web server group
/// can serve them directly (SPEC.md §9.1, mode B).
pub fn write(output_dir: &Path, site: &Site, previous: &Site, first: bool) -> io::Result<()> {
    for (url, file) in &site.files {
        // Served by the built-in server only: never put it into the
        // directory a proxy may serve without authentication.
        if url == "/metrics" {
            continue;
        }
        if previous
            .files
            .get(url)
            .is_some_and(|old| old.body == file.body)
        {
            continue;
        }
        let path = disk_path(output_dir, url);
        if let Some(parent) = path.parent() {
            DirBuilder::new()
                .recursive(true)
                .mode(0o750)
                .create(parent)?;
        }
        write_atomic(&path, &file.body, 0o640, Durability::Regenerated)?;
    }
    if first {
        remove_stale(output_dir, site)?;
    }
    Ok(())
}

/// A directory containing nothing but files kinomi generates for a page.
fn is_generated_page_dir(dir: &Path) -> bool {
    let names = |d: &Path| -> Option<Vec<String>> {
        fs::read_dir(d)
            .ok()?
            .flatten()
            .map(|e| e.file_name().into_string().ok())
            .collect()
    };
    let Some(top) = names(dir) else { return false };
    top.iter().all(|n| match n.as_str() {
        "index.html" | "status.json" | "feed.atom" => true,
        "badge" => names(&dir.join("badge")).is_some_and(|b| b.iter().all(|f| f.ends_with(".svg"))),
        _ => false,
    })
}

/// Remove what removed pages and monitors left behind: directories of
/// pages that no longer exist (only if they look exactly like ours), stale
/// badges, and the private assets once there are no private pages.
fn remove_stale(output_dir: &Path, site: &Site) -> io::Result<()> {
    for top in ["public", "private"] {
        let Ok(entries) = fs::read_dir(output_dir.join(top)) else {
            continue;
        };
        for entry in entries.flatten() {
            let name = entry.file_name();
            let Some(id) = name.to_str() else { continue };
            let url = if top == "public" {
                format!("/{id}/")
            } else {
                format!("/private/{id}/")
            };
            let dir = entry.path();
            if id == "assets" {
                // Assets of private pages, after the last one was removed.
                remove_files_not_in(&dir, &format!("{}assets/", url_root(top)), site, |n| {
                    n == "kinomi.css" || n == "favicon.svg"
                })?;
                continue;
            }
            if !is_valid_id(id) {
                continue;
            }
            if site.files.contains_key(&url) {
                // Badges of monitors no longer on the page (or show_badges off).
                remove_files_not_in(&dir.join("badge"), &format!("{url}badge/"), site, |n| {
                    n.ends_with(".svg")
                })?;
            } else if is_generated_page_dir(&dir) {
                fs::remove_dir_all(&dir)?;
            }
        }
    }
    Ok(())
}

fn url_root(top: &str) -> &'static str {
    if top == "public" { "/" } else { "/private/" }
}

/// Remove the files of `dir` that kinomi writes (`ours`) but that are not
/// part of `site` (at URL `url_prefix` + name), and then `dir` if it is empty.
fn remove_files_not_in(
    dir: &Path,
    url_prefix: &str,
    site: &Site,
    ours: impl Fn(&str) -> bool,
) -> io::Result<()> {
    let Ok(entries) = fs::read_dir(dir) else {
        return Ok(());
    };
    for entry in entries.flatten() {
        let name = entry.file_name();
        let Some(name) = name.to_str() else { continue };
        let is_file = entry.file_type().is_ok_and(|t| t.is_file());
        if is_file && ours(name) && !site.files.contains_key(&format!("{url_prefix}{name}")) {
            fs::remove_file(entry.path())?;
        }
    }
    // Only succeeds if nothing else is left in it.
    let _ = fs::remove_dir(dir);
    Ok(())
}

/// What is on disk, so that only changed files are written.
struct Written {
    site: Arc<Site>,
    /// Nothing written successfully yet: stale pages are still to be removed.
    first: bool,
}

impl Default for Written {
    fn default() -> Self {
        Written {
            site: Arc::new(Site::default()),
            first: true,
        }
    }
}

impl Written {
    fn update(&mut self, output_dir: &Path, site: &Arc<Site>) -> io::Result<()> {
        match write(output_dir, site, &self.site, self.first) {
            Ok(()) => {
                self.site = site.clone();
                self.first = false;
                Ok(())
            }
            Err(e) => {
                // Not known what made it to disk: write everything again next
                // time, and clean up after the first complete write.
                self.site = Arc::new(Site::default());
                Err(e)
            }
        }
    }
}

/// Render every snapshot received, write the files and publish the site.
pub fn spawn(
    renderer: Renderer,
    snapshots: Receiver<Snapshot>,
    published: Published,
    render_ms: Arc<AtomicU64>,
) {
    let spawned = thread::Builder::new()
        .name("renderer".into())
        .spawn(move || {
            let _ = DirBuilder::new()
                .recursive(true)
                .mode(0o750)
                .create(&renderer.output_dir);
            let _ = fs::set_permissions(&renderer.output_dir, fs::Permissions::from_mode(0o750));
            let mut written = Written::default();
            for snap in snapshots {
                let start = Instant::now();
                let site = Arc::new(renderer.build(&snap));
                if let Err(e) = written.update(&renderer.output_dir, &site) {
                    eprintln!(
                        "error: cannot write status pages to {}: {e}",
                        renderer.output_dir.display()
                    );
                }
                if let Ok(mut current) = published.write() {
                    *current = site;
                }
                render_ms.store(
                    u64::try_from(start.elapsed().as_millis()).unwrap_or(u64::MAX),
                    Ordering::Relaxed,
                );
            }
        });
    if let Err(e) = spawned {
        eprintln!("error: cannot start the renderer: {e}");
    }
}

