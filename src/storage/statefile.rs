//! Per-monitor state files `{data_dir}/state/{monitor}.toml` (SPEC.md §7.2).
//!
//! They are derived data: human-readable, written atomically, and always
//! rebuildable from the check log. A broken state file is ignored (and the
//! log replayed instead), never fatal.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs::{self, DirBuilder};
use std::io::{self, Write};
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt};
use std::path::{Path, PathBuf};

use serde::Deserialize;

use crate::clock;
use crate::history::{Beat, BeatRecord, Bucket, History};
use crate::state::State;

/// State files larger than this are treated as broken.
const MAX_STATE_BYTES: u64 = 1024 * 1024;

pub fn state_dir(data_dir: &Path) -> PathBuf {
    data_dir.join("state")
}

pub fn path(data_dir: &Path, monitor: &str) -> PathBuf {
    state_dir(data_dir).join(format!("{monitor}.toml"))
}

/// Serialize `history` in the fixed format of SPEC.md §7.2.
pub fn to_toml(monitor: &str, h: &History) -> String {
    let mut out = String::new();
    let time = |t: i64| clock::format_rfc3339(clock::from_unix(t));
    let _ = writeln!(
        out,
        "# Generated by uptime-kinomi. Rebuild with: uptime-kinomi rebuild-state"
    );
    let _ = writeln!(out, "monitor = {}", quote(monitor));
    if let Some(t) = h.covered_until {
        let _ = writeln!(out, "covered_until = {}", quote(&time(t)));
        let _ = writeln!(out, "covered_events = {}", h.covered_events);
    }
    let _ = writeln!(out, "state = {}", quote(h.state.name()));
    for (key, value) in [
        ("state_since", h.state_since),
        ("last_check", h.last_check),
        ("cert_expires", h.cert_expires),
    ] {
        if let Some(t) = value {
            let _ = writeln!(out, "{key} = {}", quote(&time(t)));
        }
    }
    let _ = writeln!(out, "last_msg = {}", quote(&h.last_msg));
    if h.paused {
        let _ = writeln!(out, "paused = true");
    }
    if let Some((t, msg)) = &h.last_error {
        let _ = writeln!(out, "last_error_time = {}", quote(&time(*t)));
        let _ = writeln!(out, "last_error = {}", quote(msg));
    }
    let _ = writeln!(out, "# heartbeat bar: time, result, latency in ms");
    let _ = writeln!(out, "recent = [");
    for b in &h.recent {
        let latency = b.latency_ms.map_or("-".to_string(), |ms| ms.to_string());
        let _ = writeln!(
            out,
            "  {},",
            quote(&format!("{} {} {latency}", time(b.time), b.beat.name()))
        );
    }
    let _ = writeln!(out, "]");
    let _ = writeln!(out, "# state changes: time, new state");
    let _ = writeln!(out, "changes = [");
    for (t, state) in &h.changes {
        let _ = writeln!(
            out,
            "  {},",
            quote(&format!("{} {}", time(*t), state.name()))
        );
    }
    let _ = writeln!(out, "]");
    for (table, buckets, key) in [
        ("hourly", &h.hourly, clock::format_hour as fn(i64) -> String),
        ("daily", &h.daily, |day| {
            clock::format_date(clock::from_unix(day * 86400))
        }),
    ] {
        let _ = writeln!(out, "\n[{table}]");
        for (index, b) in buckets {
            let start = if table == "hourly" {
                index * 3600
            } else {
                *index
            };
            let _ = writeln!(
                out,
                "{} = {{ up = {}, down = {}, skipped = {}, maint = {}, avg_ms = {}, timed = {} }}",
                quote(&key(start)),
                b.up,
                b.down,
                b.skipped,
                b.maint,
                b.avg_ms().unwrap_or(0),
                b.timed
            );
        }
    }
    out
}

/// TOML basic string.
fn quote(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04X}", u32::from(c));
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct StateFile {
    monitor: String,
    covered_until: Option<String>,
    /// Missing in files of 0.4.0 and older: all events of that second.
    covered_events: Option<u32>,
    state: String,
    state_since: Option<String>,
    last_check: Option<String>,
    cert_expires: Option<String>,
    #[serde(default)]
    last_msg: String,
    #[serde(default)]
    paused: bool,
    last_error_time: Option<String>,
    last_error: Option<String>,
    #[serde(default)]
    recent: Vec<String>,
    #[serde(default)]
    changes: Vec<String>,
    #[serde(default)]
    hourly: BTreeMap<String, BucketFile>,
    #[serde(default)]
    daily: BTreeMap<String, BucketFile>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct BucketFile {
    up: u32,
    down: u32,
    skipped: u32,
    maint: u32,
    avg_ms: u32,
    timed: u32,
}

impl BucketFile {
    fn bucket(&self) -> Bucket {
        Bucket {
            up: self.up,
            down: self.down,
            skipped: self.skipped,
            maint: self.maint,
            latency_sum_ms: u64::from(self.avg_ms) * u64::from(self.timed),
            timed: self.timed,
        }
    }
}

/// Parse a state file into `history` (which brings the configured limits).
pub fn from_toml(text: &str, monitor: &str, history: &mut History) -> Result<(), String> {
    let file: StateFile = toml::from_str(text).map_err(|e| e.to_string())?;
    if file.monitor != monitor {
        return Err(format!("belongs to monitor '{}'", file.monitor));
    }
    let time = |field: &str, value: &Option<String>| -> Result<Option<i64>, String> {
        value
            .as_deref()
            .map(|v| clock::parse_rfc3339(v).ok_or_else(|| format!("invalid {field}")))
            .transpose()
    };
    let state = match State::parse(&file.state) {
        // Written by 0.4.0: MAINTENANCE is now derived from the windows, and
        // what the monitor was before the window is not in the file.
        Some(State::Maintenance) => State::Unknown,
        Some(state) => state,
        None => return Err(format!("invalid state '{}'", file.state)),
    };
    let mut changes = std::collections::VecDeque::new();
    for entry in &file.changes {
        let (t, s) = entry.split_once(' ').ok_or("invalid change entry")?;
        changes.push_back((
            clock::parse_rfc3339(t).ok_or("invalid change time")?,
            State::parse(s).ok_or("invalid change state")?,
        ));
    }
    let mut restored = History::new(history.recent_max(), 0);
    restored.restore(
        state,
        time("state_since", &file.state_since)?,
        time("last_check", &file.last_check)?,
        file.last_msg,
        time("cert_expires", &file.cert_expires)?,
        time("covered_until", &file.covered_until)?,
    );
    for entry in &file.recent {
        let mut parts = entry.split(' ');
        let (Some(t), Some(beat), Some(latency), None) =
            (parts.next(), parts.next(), parts.next(), parts.next())
        else {
            return Err("invalid recent entry".into());
        };
        restored.recent.push_back(BeatRecord {
            time: clock::parse_rfc3339(t).ok_or("invalid recent time")?,
            beat: Beat::parse(beat).ok_or("invalid recent result")?,
            latency_ms: if latency == "-" {
                None
            } else {
                Some(latency.parse().map_err(|_| "invalid recent latency")?)
            },
        });
    }
    while restored.recent.len() > history.recent_max() {
        restored.recent.pop_front();
    }
    for (key, b) in &file.hourly {
        let start = clock::parse_hour(key).ok_or("invalid hourly key")?;
        restored.hourly.insert(start.div_euclid(3600), b.bucket());
    }
    for (key, b) in &file.daily {
        let day = clock::parse_date(key).ok_or("invalid daily key")?;
        restored.daily.insert(day, b.bucket());
    }
    // Everything is parsed: only now change `history`, so a broken file
    // leaves it untouched (and the log replay fills it completely).
    let last_error = match (
        time("last_error_time", &file.last_error_time)?,
        file.last_error,
    ) {
        (Some(t), Some(msg)) => Some((t, msg)),
        (None, None) => None,
        _ => return Err("last_error and last_error_time go together".into()),
    };
    history.restore(
        restored.state,
        restored.state_since,
        restored.last_check,
        restored.last_msg,
        restored.cert_expires,
        restored.covered_until,
    );
    history.covered_events = file.covered_events.unwrap_or(u32::MAX);
    history.last_error = last_error;
    history.paused = file.paused;
    history.recent = restored.recent;
    history.hourly = restored.hourly;
    history.daily = restored.daily;
    history.changes = changes;
    Ok(())
}

/// Load the state file of `monitor` into `history`. Returns a warning if a
/// file exists but cannot be used (the log replay then fills the gap).
pub fn load(data_dir: &Path, monitor: &str, history: &mut History) -> Option<String> {
    let path = path(data_dir, monitor);
    let meta = match fs::metadata(&path) {
        Ok(meta) => meta,
        Err(e) if e.kind() == io::ErrorKind::NotFound => return None,
        Err(e) => return Some(format!("{}: {e}", path.display())),
    };
    if meta.len() > MAX_STATE_BYTES {
        return Some(format!("{}: too large, ignored", path.display()));
    }
    let result = fs::read_to_string(&path)
        .map_err(|e| e.to_string())
        .and_then(|text| from_toml(&text, monitor, history));
    result
        .err()
        .map(|e| format!("{}: {e}; rebuilding from the log", path.display()))
}

/// Write the state file atomically (temporary file + rename).
pub fn save(data_dir: &Path, monitor: &str, history: &History) -> io::Result<()> {
    let dir = state_dir(data_dir);
    DirBuilder::new().recursive(true).mode(0o700).create(&dir)?;
    write_atomic(
        &path(data_dir, monitor),
        to_toml(monitor, history).as_bytes(),
        0o600,
        Durability::Durable,
    )
}

/// Durability of [`write_atomic`].
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Durability {
    /// fsync before the rename: the file survives a power cut (state files).
    Durable,
    /// No fsync: for files that are regenerated anyway (status pages); spares
    /// SD cards when `output_dir` is not on a tmpfs.
    Regenerated,
}

/// Write `content` to `path` via a temporary file in the same directory and
/// rename, so readers never see a partial file.
pub fn write_atomic(path: &Path, content: &[u8], mode: u32, sync: Durability) -> io::Result<()> {
    let mut name = path.file_name().unwrap_or_default().to_os_string();
    name.push(format!(".tmp-{}", std::process::id()));
    let tmp = path.with_file_name(name);
    let result = (|| {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(mode)
            .open(&tmp)?;
        file.write_all(content)?;
        if sync == Durability::Durable {
            file.sync_data()?;
        }
        fs::rename(&tmp, path)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::state::LogResult;
    use crate::testutil::TestDir;

    const T: i64 = 1_792_678_991;

    fn sample() -> History {
        let mut h = History::new(50, 400);
        h.record_check(
            T - 2 * 86400,
            LogResult::Up,
            Some(120),
            "HTTP 200",
            Some(T + 30 * 86400),
        );
        h.record_check(T - 3600, LogResult::Fail, Some(5000), "timeout", None);
        h.record_check(T, LogResult::Down, None, "a \"quoted\"\nmessage", None);
        h.record_skip(T + 10, 1);
        h
    }

    #[test]
    fn round_trip() {
        let h = sample();
        let text = to_toml("blog", &h);
        let mut restored = History::new(50, 400);
        from_toml(&text, "blog", &mut restored).unwrap();
        assert_eq!(restored, h);
        // Files of 0.4.0 and older have no covered_events: the whole second
        // of covered_until counts as included, as before.
        let old: String = text
            .lines()
            .filter(|l| !l.starts_with("covered_events"))
            .map(|l| format!("{l}\n"))
            .collect();
        let mut restored = History::new(50, 400);
        from_toml(&old, "blog", &mut restored).unwrap();
        assert_eq!(restored.covered_events, u32::MAX);

        // 0.4.0 stored MAINTENANCE as a state; it is not one any more.
        let maint = text.replace("state = \"DOWN\"", "state = \"MAINTENANCE\"");
        let mut restored = History::new(50, 400);
        from_toml(&maint, "blog", &mut restored).unwrap();
        assert_eq!(restored.state, State::Unknown);
    }

    #[test]
    fn readable_format() {
        let text = to_toml("blog", &sample());
        assert!(text.starts_with("# Generated by uptime-kinomi."), "{text}");
        assert!(text.contains("monitor = \"blog\"\n"));
        assert!(text.contains("state = \"DOWN\"\n"));
        assert!(text.contains("  \"2026-10-22T14:23:11Z DOWN -\",\n"));
        assert!(text.contains("\"2026-10-22T13\" = { up = 1, down = 0, skipped = 0, maint = 0, avg_ms = 0, timed = 0 }"));
        assert!(text.contains("[daily]\n\"2026-10-20\" = { up = 1,"));
    }

    #[test]
    fn broken_files_are_rejected() {
        let good = to_toml("blog", &sample());
        for broken in [
            good.replace("monitor = \"blog\"", "monitor = \"other\""),
            good.replace("state = \"DOWN\"", "state = \"MAYBE\""),
            good.replace("DOWN -", "DOWN"),
            good.replace("2026-10-22T13\"", "2026-10-22T25\""),
            good.replace("timed = 1 }", "timed = 1, extra = 2 }"),
            good.lines()
                .filter(|l| !l.starts_with("last_error = "))
                .map(|l| format!("{l}\n"))
                .collect(),
            good.replace("last_error_time = \"", "last_error_time = \"x"),
            "garbage".to_string(),
        ] {
            let mut h = History::new(50, 400);
            assert!(from_toml(&broken, "blog", &mut h).is_err(), "{broken}");
            assert_eq!(h, History::new(50, 400), "history must be untouched");
        }
    }

    #[test]
    fn save_and_load() {
        let dir = TestDir::new("statefile");
        let h = sample();
        save(dir.path(), "blog", &h).unwrap();
        let mut loaded = History::new(50, 400);
        assert_eq!(load(dir.path(), "blog", &mut loaded), None);
        assert_eq!(loaded, h);
        assert_eq!(
            load(dir.path(), "missing", &mut History::new(50, 400)),
            None
        );
        fs::write(path(dir.path(), "bad"), "garbage").unwrap();
        assert!(load(dir.path(), "bad", &mut History::new(50, 400)).is_some());
        // No temporary files left behind.
        assert_eq!(fs::read_dir(state_dir(dir.path())).unwrap().count(), 2);
    }
}
